impl Icon {
    /// Coverage mask of `px` by `px` pixels.
    pub(crate) fn rasterize(self, px: u32) -> (Vec<u8>, u32, u32) {
        let n = px.max(1);
        let mut out = vec![0u8; (n * n) as usize];
        let scale = Transform::scale(n as f32 / 24.0, n as f32 / 24.0);
        for part in self.parts() {
            let mut buf = vec![0u8; out.len()];
            match part {
                Part::Fill(d) => {
                    Mask::new(*d)
                        .size(n, n)
                        .transform(Some(scale))
                        .style(Fill::NonZero)
                        .render_into(&mut buf, None);
                }
                Part::Line(d) => {
                    Mask::new(*d)
                        .size(n, n)
                        .transform(Some(scale))
                        .style(Stroke::new(1.9).cap(Cap::Round).join(Join::Round))
                        .render_into(&mut buf, None);
                }
            }
            for (o, b) in out.iter_mut().zip(&buf) {
                *o = (*o).max(*b);
            }
        }
        (out, n, n)
    }
}

