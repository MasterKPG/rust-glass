    fn every_icon_draws_something() {
        for i in Icon::ALL {
            let (data, ..) = i.rasterize(48);
            let covered = data.iter().filter(|v| **v > 64).count();
            assert!(covered > 30, "{} is nearly empty ({covered})", i.name());
        }
    }
